export const ashStars: ConstellationStar[] = authored.map(
    ([id, name, description, parent, minimumLevel, , , ability]) => ({
        ...star(
            'prayer_grave',
            id,
            name,
            description,
            [parent],
            [],
            'pray_grave'
        ),
        minimumLevel,
        results: [description],
        ...(id === 'brand' ? { acquisition: 'event' as const } : {}),
        ...(ability === undefined
            ? {}
            : {
                  acquisition: 'event' as const,
                  kind: 'ability' as const,
                  effectType: 'active' as const,
                  activationAbilityId: ability,
              }),
    })
)

