/** Mother insight reveals outcomes separately from the star's in-world description. */
export function withPrayerLore(node: ConstellationStar): ConstellationStar {
    if (node.constellationId !== 'prayer') {
        return node
    }
    const description = descriptions[node.id.slice('prayer.'.length)]
    return description === undefined
        ? node
        : {
              ...node,
              description,
              results:
                  node.results ??
                  node.description.split(/(?<=[.!?])\s+(?=[А-ЯЁ])/u),
          }
}
