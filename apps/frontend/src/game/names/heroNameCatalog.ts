function namesFor(language: HeroNameLanguage) {
    const short = [...HERO_GIVEN_NAMES[language]]
    const withEpithet = short
        .flatMap((name) => HERO_NAME_EPITHETS[language].map((epithet) => `${name} ${epithet}`))
        .filter((name) => name.length <= MAX_GENERATED_HERO_NAME_LENGTH)
    return { short: Object.freeze(short), withEpithet: Object.freeze(withEpithet) }
}

export const HERO_NAME_POOLS = Object.freeze({ ru: namesFor('ru'), en: namesFor('en') })
