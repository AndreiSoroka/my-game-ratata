const APPEARANCE_SOURCES = {
    solid: 'solidSrc',
    'transparent-border': 'transparentBorderSrc',
    'transparent-center': 'transparentCenterSrc',
} as const

export type FantasyPanelVariant = keyof typeof FANTASY_PANEL_VARIANTS
export type FantasyPanelAppearance = keyof typeof APPEARANCE_SOURCES

export function resolveFantasyPanel(
    panel?: string,
    appearance?: string
): {
    key: FantasyPanelVariant
    appearance: FantasyPanelAppearance
    src: string
    slice: number
} {
    const key = (
        typeof panel === 'string' && Object.hasOwn(FANTASY_PANEL_VARIANTS, panel)
            ? panel
            : 'panel-026'
    ) as FantasyPanelVariant
    const resolvedAppearance = (
        typeof appearance === 'string' && Object.hasOwn(APPEARANCE_SOURCES, appearance)
            ? appearance
            : 'solid'
    ) as FantasyPanelAppearance
    const metadata = FANTASY_PANEL_VARIANTS[key]
    return {
        key,
        appearance: resolvedAppearance,
        src: metadata[APPEARANCE_SOURCES[resolvedAppearance]],
        slice: metadata.slice,
    }
}
